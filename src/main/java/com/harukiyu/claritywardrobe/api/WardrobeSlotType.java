package com.harukiyu.claritywardrobe.api;

/**
 * Represents the supported cosmetic slots in ClarityWardrobe.
 */
public enum WardrobeSlotType {
    /**
     * Cosmetic hat or helmet worn visually on the head without altering combat armor.
     */
    HELMET,

    /**
     * Cosmetic backpack, wings, or accessory rendered on the player's back.
     */
    BACKPACK
}
